def feedback(name, correct, total):
    """조건 하나의 결과 문구. 조건 이름은 화면이 따로 보여 주므로 문구에 넣지 않는다"""
    if correct >= total:
        return '잘 지켜졌어요.' if total == 1 else f'{total}회 모두 잘 지켜졌어요.'
    bad = total - correct
    if total == 1:
        prefix = ''
    elif bad == total:
        prefix = f'{total}회 모두 '
    else:
        prefix = f'{total}회 중 {bad}회는 '
    verdict = prefix + ISSUES.get(name, '기준과 달라 보여요.')
    tip = TIPS.get(name, '')
    return f'{verdict} {tip}' if tip else verdict
