-- PostgreSQL 버전 (H2 MODE=PostgreSQL 호환)
-- 1) 소셜 전용 회원은 비밀번호가 없으므로 password_hash NULL 허용
ALTER TABLE users ALTER COLUMN password_hash DROP NOT NULL;

-- 2) 소셜 계정 연동 테이블 (Google / Naver / Kakao)
CREATE TABLE user_social_accounts (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id           BIGINT       NOT NULL,
    provider          VARCHAR(20)  NOT NULL,
    provider_user_id  VARCHAR(128) NOT NULL,
    provider_email    VARCHAR(254) NULL,
    created_at        TIMESTAMP(6) NOT NULL,
    updated_at        TIMESTAMP(6) NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT uk_social_provider_user UNIQUE (provider, provider_user_id),
    CONSTRAINT uk_social_user_provider UNIQUE (user_id, provider),
    CONSTRAINT fk_social_accounts_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_social_accounts_user_id
    ON user_social_accounts (user_id);
