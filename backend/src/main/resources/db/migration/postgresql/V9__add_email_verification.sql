-- PostgreSQL 버전 (H2 MODE=PostgreSQL 호환)
-- 1) 회원 테이블에 이메일 인증 상태 컬럼 추가
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE users ADD COLUMN email_verified_at TIMESTAMP(6) NULL;

-- 2) 기존 가입자는 이미 사용 중인 계정이므로 일괄 인증 완료로 전환
UPDATE users
SET email_verified = TRUE,
    email_verified_at = created_at
WHERE email_verified = FALSE;

-- 3) 이메일 인증 토큰 테이블 (원문 대신 SHA-256 해시만 저장)
CREATE TABLE email_verification_tokens (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    user_id     BIGINT       NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL,
    expires_at  TIMESTAMP(6) NOT NULL,
    used_at     TIMESTAMP(6) NULL,
    created_at  TIMESTAMP(6) NOT NULL,
    updated_at  TIMESTAMP(6) NOT NULL,

    PRIMARY KEY (id),

    CONSTRAINT uk_email_verif_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_email_verif_tokens_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

-- 회원별 최근 발송 시간(재발송 쿨다운)·미사용 토큰 정리 조회용
CREATE INDEX idx_email_verif_user_created
    ON email_verification_tokens (user_id, created_at);

CREATE INDEX idx_email_verif_expires_at
    ON email_verification_tokens (expires_at);
