-- PostgreSQL 버전 (H2 MODE=PostgreSQL 호환)
-- 운동 루틴·세션 (FR-WORK-01, BR-17, SDD 8.1). 운동 기록(workout_logs)은 별도 마이그레이션(최원석)에서 추가한다.

CREATE TABLE workout_routines (
    id                 BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id            BIGINT        NOT NULL,
    goal               VARCHAR(20)   NOT NULL,
    level              VARCHAR(20)   NOT NULL,
    days_per_week      INT           NOT NULL,
    session_minutes    INT           NOT NULL,
    equipment_snapshot VARCHAR(500)  NOT NULL,
    injuries_snapshot  VARCHAR(500)  NOT NULL,
    unknown_injury     BOOLEAN       NOT NULL DEFAULT FALSE,
    intensity_cap      INT           NOT NULL,
    source             VARCHAR(20)   NOT NULL,
    rule_version       VARCHAR(20)   NOT NULL,
    status             VARCHAR(20)   NOT NULL,
    start_date         DATE          NOT NULL,
    planned_until      DATE          NOT NULL,
    created_at         TIMESTAMP(6)  NOT NULL,
    updated_at         TIMESTAMP(6)  NOT NULL,

    PRIMARY KEY (id),
    CONSTRAINT fk_workout_routines_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_workout_routines_days CHECK (days_per_week BETWEEN 2 AND 6),
    CONSTRAINT ck_workout_routines_minutes CHECK (session_minutes IN (15, 30, 45, 60))
);

CREATE INDEX idx_workout_routines_user_status ON workout_routines (user_id, status);

-- active_key: 활성 세션이면 session_date, 교체되면 NULL. NULL끼리는 겹쳐도 되므로
-- (user_id, active_key) 유일 제약으로 "같은 사용자·날짜의 활성 세션 중복 방지"를 구현한다 (H2·PostgreSQL 공통).
CREATE TABLE workout_sessions (
    id              BIGINT         GENERATED BY DEFAULT AS IDENTITY,
    routine_id      BIGINT         NOT NULL,
    user_id         BIGINT         NOT NULL,
    session_date    DATE           NOT NULL,
    focus_area      VARCHAR(20)    NOT NULL,
    title           VARCHAR(100)   NOT NULL,
    planned_minutes INT            NOT NULL,
    items           VARCHAR(4000)  NOT NULL,
    source          VARCHAR(20)    NOT NULL,
    adjusted        BOOLEAN        NOT NULL DEFAULT FALSE,
    adjust_note     VARCHAR(200)   NULL,
    active_key      DATE           NULL,
    created_at      TIMESTAMP(6)   NOT NULL,
    updated_at      TIMESTAMP(6)   NOT NULL,

    PRIMARY KEY (id),
    CONSTRAINT fk_workout_sessions_routine FOREIGN KEY (routine_id) REFERENCES workout_routines (id),
    CONSTRAINT fk_workout_sessions_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_workout_sessions_user_active UNIQUE (user_id, active_key)
);

CREATE INDEX idx_workout_sessions_user_date ON workout_sessions (user_id, session_date);
CREATE INDEX idx_workout_sessions_routine ON workout_sessions (routine_id);
