-- PostgreSQL 버전 (H2 MODE=PostgreSQL 호환)
-- [운동기록] 운동 완료 기록 (FR-WORK-03·04, BR-18, SDD 5.8). 중량 단위는 kg(NUMERIC(6,2))로 통일.

CREATE TABLE workout_logs (
    id             BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    user_id        BIGINT        NOT NULL,
    session_id     BIGINT        NOT NULL,
    workout_date   DATE          NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    actual_minutes INT           NOT NULL DEFAULT 0,
    weight_kg      NUMERIC(6,2)  NULL,
    logged_at      TIMESTAMP(6)  NOT NULL,
    created_at     TIMESTAMP(6)  NOT NULL,
    updated_at     TIMESTAMP(6)  NOT NULL,

    PRIMARY KEY (id),
    CONSTRAINT fk_workout_logs_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_workout_logs_session FOREIGN KEY (session_id) REFERENCES workout_sessions (id),
    CONSTRAINT uk_workout_logs_user_session UNIQUE (user_id, session_id),
    CONSTRAINT ck_workout_logs_actual_minutes CHECK (actual_minutes >= 0),
    CONSTRAINT ck_workout_logs_weight_kg CHECK (weight_kg IS NULL OR weight_kg >= 0)
);

CREATE INDEX idx_workout_logs_user_date ON workout_logs (user_id, workout_date);
