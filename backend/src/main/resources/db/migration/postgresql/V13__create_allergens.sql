-- 알레르기 유발물질 사전 (MEALFIT-138). 모든 사용자가 같이 쓰는 참조 데이터라 user_id가 없다.
-- 근거: 식품표시광고법 시행규칙 별표 2 Ⅰ.1.가 19종(CURRENT) + 식약처 공고 제2026-386호 개정 예고 4종(PROPOSED, 미리 적용).
-- 카테고리는 화면 묶음용 분류이고 고시 기준은 개별 항목이다. 회원 선택은 개별 항목으로만 저장한다.
-- 별칭과 재료 연결은 팀이 작성한 것이며 고시 원문이 아니다. 재료 사전이 없으므로 재료는 이름(텍스트)으로 연결한다.

CREATE TABLE allergens (
    id               BIGINT        GENERATED BY DEFAULT AS IDENTITY,
    code             VARCHAR(30)   NOT NULL,
    name             VARCHAR(50)   NOT NULL,
    category         VARCHAR(30)   NOT NULL,
    category_order   INT           NOT NULL,
    display_order    INT           NOT NULL,
    select_all       BOOLEAN       NOT NULL, -- 묶음의 [전체 선택]에 포함되는지
    legal_status     VARCHAR(20)   NOT NULL, -- CURRENT(현행 고시) / PROPOSED(개정 예고)
    legal_condition  VARCHAR(200)  NULL,

    PRIMARY KEY (id),
    CONSTRAINT uk_allergens_code UNIQUE (code),
    CONSTRAINT uk_allergens_name UNIQUE (name),
    CONSTRAINT ck_allergens_legal_status CHECK (legal_status IN ('CURRENT', 'PROPOSED'))
);

-- 검색용 별칭 (예: 계란 → 알류, 굴 → 조개류). 별칭은 한 알레르기에만 속한다.
CREATE TABLE allergen_aliases (
    allergen_id BIGINT       NOT NULL,
    alias       VARCHAR(50)  NOT NULL,

    PRIMARY KEY (allergen_id, alias),
    CONSTRAINT uk_allergen_aliases_alias UNIQUE (alias),
    CONSTRAINT fk_allergen_aliases_allergen FOREIGN KEY (allergen_id) REFERENCES allergens (id) ON DELETE CASCADE
);

-- 재료 이름 → 알레르기. CONTAINS = 확실히 포함, MAY_CONTAIN = 제품에 따라 포함될 수 있어 확인 필요.
CREATE TABLE ingredient_allergens (
    ingredient_name VARCHAR(100) NOT NULL,
    allergen_id     BIGINT       NOT NULL,
    certainty       VARCHAR(20)  NOT NULL,

    PRIMARY KEY (ingredient_name, allergen_id),
    CONSTRAINT ck_ingredient_allergens_certainty CHECK (certainty IN ('CONTAINS', 'MAY_CONTAIN')),
    CONSTRAINT fk_ingredient_allergens_allergen FOREIGN KEY (allergen_id) REFERENCES allergens (id) ON DELETE CASCADE
);
CREATE INDEX idx_ingredient_allergens_allergen ON ingredient_allergens (allergen_id);

